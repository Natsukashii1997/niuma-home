// 卡片正文在 docs/打法库/P*.md（结构见 P0201-早鸟价.md）。第二行是隐藏元信息，页面不展示：
// <!-- 编号 | 类别 N | 阶段 新签/续费/通用 | 障碍 主… ; 辅… | 机制 M.. M.. -->，障碍编号用于筛选和 T13 选打法。

// 解析一张卡片的 Markdown 原文：标题、类别、阶段、主 / 辅障碍、机制（首个为主）、定位段、正文。前端和 T13 共用。
const META = /^<!-- (P\d{4}) \| 类别 (\d+) \| 阶段 (新签|续费|通用) \| 障碍 ([^|]+?) \| 机制 ([^|]+?) -->$/;
export function parseCard(text) {
  const lines = String(text).replace(/\r/g, "").split("\n");
  const m = (lines[1] || "").match(META);
  if (!m) return null;
  const [, id, cat, stage, bar, mech] = m;
  const [main = "", sub = ""] = bar.split(";").map((s) => s.trim());
  const body = lines.slice(2).join("\n").trim();
  const lead = (body.match(/^\*\*定位\*\*：(.+)$/m) || [])[1] || "";
  return {
    id, cat: Number(cat), stage, name: lines[0].replace(/^#\s*/, "").split(" · ")[0],
    barriers: { main: main.split(/\s+/).filter(Boolean), sub: sub.split(/\s+/).filter(Boolean) },
    mechs: mech.trim().split(/\s+/), lead, body,
  };
}
